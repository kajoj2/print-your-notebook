// Turns the website's configuration into files for the Typst compiler:
//   /config/notebook.toml – the same schema that lib/config.typ reads,
//   /main.typ              – an insert assembled from the templates in templates/.
// Text typed by the user (the title) goes through sys.inputs, never into the source.

import { monthAt, parseIsoDate } from './calendar';
import { MAX_STAPLED_SHEETS, type NotebookConfig, type Section } from './config';
import {
  DEFAULT_PRINTER,
  MARKS,
  NUMBER_BOX,
  PAPER_SIZES,
  fitToPrinter,
  sheetLayout,
  type PrinterProfile,
} from './printer';
import { notesPages, weekSpan } from './volume';

export const MAIN_PATH = '/main.typ';
export const CONFIG_PATH = '/config/notebook.toml';

// store names from the shopping list: user text, so through sys.inputs like the title
const STORES_INPUT = 'shopping-stores';
const shoppingStores = (cfg: NotebookConfig): string[] =>
  cfg.sections.find((s) => s.type === 'shopping')?.stores ?? [];
const storesInput = `json(bytes(sys.inputs.at(${JSON.stringify(STORES_INPUT)}, default: "[]")))`;

export interface TypstInput {
  files: Record<string, string>;
  inputs: Record<string, string>;
}

export function toTypst(cfg: NotebookConfig, printer = DEFAULT_PRINTER): TypstInput {
  return {
    files: { [CONFIG_PATH]: toToml(cfg, printer), [MAIN_PATH]: toMain(cfg) },
    inputs: typstInputs(cfg),
  };
}

// user text for sys.inputs
export function typstInputs(cfg: NotebookConfig): Record<string, string> {
  return { title: cfg.title, [STORES_INPUT]: JSON.stringify(shoppingStores(cfg)) };
}

const num = (x: number) => (Number.isInteger(x) ? x.toFixed(1) : String(x));
const str = (s: string) => JSON.stringify(s);

// Page number position: the box centre halfway into the bottom margin, but no closer
// to the edge than half a box above the unprintable area; x aligned to the outer
// margin, also not inside the unprintable area.
export function numberPlacement(cfg: NotebookConfig, unprintable = 0): { x: number; y: number } {
  const half = NUMBER_BOX / 2;
  return {
    x: Math.max(2, unprintable, cfg.margins.outer - 1),
    y: Math.min(Math.max(cfg.margins.bottom / 2, unprintable + half), cfg.margins.bottom - half),
  };
}

// Margins are first fitted to the printer (fitToPrinter), so the checks in
// lib/config.typ (margin and page number outside the unprintable area) pass.
// target 'preview': insert pages only, without the sheet and marks.
// target 'print': a real sheet from the profile, for imposition (impose.typ).
export function toToml(
  cfg: NotebookConfig,
  printer = DEFAULT_PRINTER,
  target: 'preview' | 'print' = 'preview',
): string {
  const fitted = fitToPrinter(cfg, printer).config;
  const layout = sheetLayout(fitted, printer);
  const print = target === 'print';
  const u = printer.unprintable;
  const n = numberPlacement(fitted, u);
  const paper = PAPER_SIZES[printer.paper];
  return `# Generated by the web generator.
${designToml(fitted, 'web', `from_edge_x = ${num(n.x)}\nfrom_edge_y = ${num(n.y)}\n`, print && layout.stacked)}
${
  print
    ? `# Sheet from the printer profile, in landscape (lib/sheet.typ rotates it for stacked).
[printer]
sheet_width = ${num(paper.width)}
sheet_height = ${num(paper.height)}`
    : `# Preview: a large sheet, so that the "format fits on the sheet" check in lib/config.typ
# doesn't block the preview (sheetLayout reports it in the panel).
[printer]
sheet_width = 2000.0
sheet_height = 2000.0`
}
unprintable = ${num(u)}

[duplex]
dx = ${num(printer.dx)}
dy = ${num(printer.dy)}
even_reverse = ${printer.evenReverse}
rotate_back = ${tomlRotateBack(printer, layout.stacked)}
max_sheets = ${MAX_STAPLED_SHEETS}

[marks]
enabled = ${print}
color = "#8a8a8a"
width = 0.2
length = ${num(MARKS.length)}
gap = ${num(MARKS.gap)}
band_start = ${num(layout.bandStart)}
band_length = ${num(MARKS.bandLength)}
`;
}

// lib/sheet.typ rotates the back of a stacked sheet by 180° (back-rotated = rotate_back != stacked),
// because with manual duplex the sheet turns around its short side, and the insert around its spine
// along the long one. With automatic duplex the printer itself flips the sheet around
// the fold (as the wizard instructs), so that rotation doesn't apply. rotateBack in the profile is
// an extra rotation, the same for every format.
export function tomlRotateBack(printer: PrinterProfile, stacked: boolean): boolean {
  return printer.duplex === 'auto' ? printer.rotateBack !== stacked : printer.rotateBack;
}

// Appearance settings shared by the website and the insert for printing. `format` is the format name:
// "web" on the website; in the CLI a preset (regular/passport/pocket), so that stacked works.
function designToml(
  cfg: NotebookConfig,
  format: string,
  numberPlacement: string,
  stacked = false,
): string {
  const { margins: m, grid: g } = cfg;
  const custom = format === 'web' || format === 'custom';
  return `[insert]
format = ${str(format)}
pages = ${insertPages(cfg)}
lang = ${str(cfg.lang)}
${
  custom
    ? `
[formats.${format}]
width = ${num(cfg.format.width)}
height = ${num(cfg.format.height)}
${stacked ? 'stacked = true\n' : ''}`
    : ''
}
[margins]
top = ${num(m.top)}
bottom = ${num(m.bottom)}
inner = ${num(m.inner)}
outer = ${num(m.outer)}

[grid]
type = ${str(g.kind)}
spacing = ${num(g.spacing)}
dot_diameter = ${num(g.dotDiameter)}
line_width = ${num(g.lineWidth)}
color = ${str(g.color)}
accent = ${str(g.accent)}

[ink]
text = "#000000"
line = ${str(cfg.ink.color)}
line_width = 0.15

[font]
family = ${str(cfg.font.family)}
size = ${num(cfg.font.size)}

[page_numbers]
enabled = ${cfg.numbering.enabled}
size = ${num(cfg.numbering.size)}
color = "#000000"
${numberPlacement}position = ${str(cfg.numbering.position)}

[calendar]
year = ${cfg.year}
week_start = ${str(cfg.weekStart)}
`;
}

// An insert for printing from the CLI (`just from-web`): inserts/<name>.typ and inserts/<name>.toml.
// The TOML only holds the appearance; printer, duplex, marks and page number position
// (no closer to the edge than the unprintable area) stay from config/notebook.toml.
export function toInsertFiles(cfg: NotebookConfig): { typ: string; toml: string } {
  const preset = cfg.format.preset;
  const toml = `# Generated by \`just from-web\`. You can edit it by hand; missing
# settings (printer, duplex, marks, page number position) come from config/notebook.toml.
${designToml(cfg, preset, '')}`;
  const typ = toMain(cfg)
    .replace(
      '// Generated by the web generator.',
      '// Generated by `just from-web`. You can edit it by hand.',
    )
    .replace(/sys\.inputs\.at\("title", default: "[^"]*"\)/g, () => typstString(cfg.title))
    .replace(storesInput, () => typstArray(shoppingStores(cfg)));
  // every new piece of user text in sys.inputs needs its own literal here, otherwise in the CLI
  // it would come out empty
  if (typ.includes('sys.inputs')) throw new Error('toInsertFiles: unhandled sys.inputs');
  return { typ, toml };
}

const typstArray = (xs: readonly string[]) =>
  xs.length === 0 ? '()' : `(${xs.map(typstString).join(', ')},)`;

// A Typst string literal (the title in the insert file, which the user edits themselves).
export function typstString(s: string): string {
  const esc = s.replace(
    /[\\"\n\r\t]/g,
    (c) => ({ '\\': '\\\\', '"': '\\"', '\n': '\\n', '\r': '\\r', '\t': '\\t' })[c]!,
  );
  return `"${esc}"`;
}

// default page count of simple inserts in lib/config.typ (must be >= 1)
function insertPages(cfg: NotebookConfig): number {
  return Math.max(1, notesPages(cfg));
}

