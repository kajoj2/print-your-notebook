// A Typst array of strings; a single-item one needs a comma: ("a",).
const strArray = (xs: readonly string[]) =>
  xs.length === 0 ? '()' : `(${xs.map(str).join(', ')},)`;
const gridArg = (g: string) => (g === 'auto' ? 'auto' : str(g));

const repeat = (n: number, page: string) => `#pages(..range(${n}).map(_ => ${page}))`;

function monthPages(cfg: NotebookConfig, startMonth: number, count: number, fn: string): string {
  const items = Array.from({ length: count }, (_, i) => {
    const [y, m] = monthAt(cfg.year, startMonth, i);
    return `${fn}(year: ${y}, month: ${m})`;
  });
  return `#pages(${items.join(', ')})`;
}

export function sectionBody(cfg: NotebookConfig, s: Section): string {
  switch (s.type) {
    case 'title':
      return `#title-page(title: sys.inputs.at("title", default: ""), owner: ${s.owner})`;
    case 'index':
      return repeat(s.pages, 'index-page()');
    case 'year':
      return '#year-page()';
    case 'future-log':
      return `#future-log-spread(start: ${s.startMonth})`;
    case 'months':
      return monthPages(cfg, s.startMonth, s.count, 'month-page');
    case 'weeks': {
      const [start, end] = weekSpan(cfg.year, s.startWeek, s.count);
      return `#for monday in cal.iso-week-mondays(${cfg.year}).slice(${start - 1}, ${end}) { week-spread(monday) }`;
    }
    case 'daily': {
      const [y, m, d] = parseIsoDate(s.startDate) ?? [cfg.year, 1, 1];
      return `#day-pages(cal.date(${y}, ${m}, ${d}), ${s.count})`;
    }
    case 'habits': {
      const items = Array.from({ length: s.count }, (_, i) => {
        const [y, m] = monthAt(cfg.year, s.startMonth, i);
        return `habit-page(year: ${y}, month: ${m}, habits: ${s.habits})`;
      });
      return `#pages(${items.join(', ')})`;
    }
    case 'budget':
      return monthPages(cfg, s.startMonth, s.count, 'budget-page');
    case 'todo':
      return repeat(s.pages, 'todo-page()');
    case 'cornell':
      return repeat(s.pages, 'cornell-page()');
    case 'travel':
      return repeat(s.pages, 'travel-page()');
    case 'reading':
      return repeat(s.pages, 'reading-page()');
    case 'notes':
      return `#grid-pages(n: ${notesPages(cfg)}, kind: ${gridArg(s.grid)})`;
    case 'pixels':
      return `#pixels-page(year: ${cfg.year}, theme: ${str(s.theme)}, legend: ${s.legend})`;
    case 'one-line':
      return `#one-line-pages(start-month: ${s.startMonth}, months: ${s.count}, years: ${s.years}, per-page: ${s.perPage})`;
    case 'birthdays':
      return `#birthday-pages(per-page: ${s.perPage}, day-column: ${s.dayColumn})`;
    case 'packing':
      return `#packing-pages(groups: ${strArray(s.groups)}, columns: ${s.columns}, pages-count: ${s.pages})`;
    case 'shopping':
      return `#shopping-pages(split: ${str(s.split)}, groups: ${strArray(s.groups)}, stores: ${storesInput}, columns: ${s.columns}, qty: ${s.qty}, pages-count: ${s.pages})`;
    case 'meals':
      return repeat(s.count, `meal-page(meals: ${s.meals}, shopping: ${s.shopping})`);
    case 'workout':
      return repeat(s.pages, `workout-page(kind: ${str(s.kind)})`);
    case 'contacts':
      return repeat(s.pages, `contact-page(fields: ${strArray(s.fields)})`);
    case 'tasting':
      return repeat(
        s.pages,
        `tasting-page(kind: ${str(s.kind)}, per-page: ${s.perPage}, wheel: ${s.wheel})`,
      );
    case 'watchlist':
      return repeat(s.pages, `watch-page(kind: ${str(s.kind)})`);
    case 'project':
      return repeat(s.pages, `project-page(steps: ${s.steps}, kind: ${gridArg(s.grid)})`);
    case 'meeting':
      return repeat(s.pages, `meeting-page(actions: ${s.actions}, kind: ${gridArg(s.grid)})`);
  }
}

// Section start marker: the page is stored in metadata, which the website reads
// with a <nb-section> query to show page ranges and jump to sections.
const marker = (type: string) =>
  `#context [#metadata((type: ${str(type)}, page: here().page())) <nb-section>]`;

// End of content and padding to the volume with grid pages. The last content page
// is marked by <nb-end> (the website reads it too, to show whether the content fits):
// here() in a block with pagebreaks would already point one page further, because a block after a full-page
// grid lands on a new page. For the same reason the first pagebreak is weak
// (the block may already sit on an empty new page). Content longer than the volume is
// only padded to a full signature (a multiple of 4).
const pad = (target: number) => `#context [#metadata((page: here().page())) <nb-end>]
#context {
  let last = query(<nb-end>).first().location().page()
  let pad = if last <= ${target} { ${target} - last } else { calc.rem(4 - calc.rem(last, 4), 4) }
  for i in range(pad) {
    pagebreak(weak: i == 0)
    fill-grid()
  }
}`;

export function toMain(cfg: NotebookConfig): string {
  // notes with no room (0 pages) drop out together with their marker
  const notes = notesPages(cfg);
  const enabled = cfg.sections.filter((s) => s.enabled && (s.type !== 'notes' || notes > 0));
  const imports = [...new Set(enabled.map((s) => IMPORTS[s.type]))];
  const body = enabled.map((s) => `${marker(s.type)}\n${sectionBody(cfg, s)}`);
  return [
    '// Generated by the web generator.',
    '#import "/lib/notebook.typ": *',
    ...imports,
    '',
    '#show: insert.with(title: sys.inputs.at("title", default: "Notes"))',
    '',
    body.join('\n#pagebreak(weak: true)\n'),
    // an empty notebook: a weak padding pagebreak wouldn't fill an empty first page,
    // so the first page gets the grid right away
    body.length ? '' : '#fill-grid()',
    pad(cfg.pages),
    '',
  ].join('\n');
}
